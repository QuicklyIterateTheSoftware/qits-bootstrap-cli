package eu.wohlben.qits.cli.bootstrap.platform;

import eu.wohlben.qits.bootstrap.graph.EdgeKind;
import eu.wohlben.qits.bootstrap.graph.ProjectGraph;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * <b>The derived boot order against {@link PlatformModel}'s three lists</b>, over the estate
 * fixture ({@code src/test/resources/estate/}, regenerated by its {@code refresh.sh}) — qits-3.
 * <p>
 * Every difference between the two is a NAMED entry below with its reason, never a silent
 * exclusion. The reason says which kind:
 * <ul>
 *   <li><b>list stale</b> — the list names what the estate no longer has, or lacks what it now
 *       has; the derivation is right.
 *   <li><b>dropped</b> — a list claim the cutover rules drop on purpose ({@link CutoverRules}):
 *       observability first, every adjacency, and pairs a subsequence assertion makes only
 *       incidentally.
 *   <li><b>list omission</b> — the list leaves out what the declarations require (decided in
 *       qits-3, see {@code LIST_OMISSION}).
 * </ul>
 */
class BootOrderDiffTest {

    private static final Path ESTATE = Path.of("src/test/resources/estate");

    private static ProjectGraph graph;
    private static BootOrder order;

    @BeforeAll
    static void derive() {
        CheckoutProjectSource source = CheckoutProjectSource.read(
                CheckoutProjectSource.Checkouts.fixture(ESTATE));
        graph = ProjectGraph.of(source, CheckoutProjectSource.RESOURCE_PROVIDERS);
        assertThat(graph.unresolved()).as("every resource resolves to a provider").isEmpty();
        assertThat(graph.ambiguous()).as("no coordinate or application is claimed twice").isEmpty();
        order = BootOrder.derive(graph, source);
    }

    /** Named differences: entry to reason. */
    private static Map<String, String> named(String... pairs) {
        Map<String, String> map = new LinkedHashMap<>();
        for (int i = 0; i < pairs.length; i += 2) {
            map.put(pairs[i], pairs[i + 1]);
        }
        return map;
    }

    private static Set<String> expected(List<String> listed, Map<String, String> notDerived,
                                        Map<String, String> onlyDerived) {
        Set<String> expected = new LinkedHashSet<>(listed);
        expected.removeAll(notDerived.keySet());
        expected.addAll(onlyDerived.keySet());
        return expected;
    }

    @Test
    void theEstateHasNoDependencyCycle() {
        assertThat(graph.components(EnumSet.of(EdgeKind.ARTIFACT, EdgeKind.RUNTIME)))
                .allSatisfy(component -> assertThat(component).hasSize(1));
    }

    @Test
    void aPnpmLockedPinIsStillAnEdge() {
        assertThat(graph.edges()).anySatisfy(edge -> {
            assertThat(edge.kind()).isEqualTo(EdgeKind.ARTIFACT);
            assertThat(edge.upstream()).isEqualTo("qits-integrations-angular-jslib");
            assertThat(edge.downstream()).isEqualTo("qits-ui-components-jslib");
            assertThat(edge.via().name()).isEqualTo("@qits/angular");
        });
    }

    @Test
    void theDeploysAreExactlyTheDeployables() {
        assertThat(order.deploys()).containsExactlyInAnyOrderElementsOf(PlatformModel.DEPLOYABLES);
    }

    /** Why a derived replay the list does not carry is the list's omission (decided in qits-3). */
    private static final String LIST_OMISSION = "list omission: pinned at a calver by another"
            + " repository; a pin is only as good as the registry behind it (RELEASE_PUBLISHERS' own"
            + " rule) — being seed-built is no exemption, integrations-quarkus, eventstream and"
            + " containers-driver are seed libraries and replays both";

    @Test
    void theReplaysAreTheReleasePublishersWithEveryDifferenceNamed() {
        Map<String, String> notDerived = named(
                "workspaces-runner-daemon",
                "list stale: retired by the target (qits-1535) and no submodule of the wrapper",
                "oci-workspace-editor",
                "list stale: nothing pins qits/workspace-editor or qits-workspace-editor-image"
                        + " (NOT_BUILT: no consumer since qits-1152)");
        Map<String, String> onlyDerived = named(
                "registries", LIST_OMISSION + " (artifacts, githost and mirror pin its jars at"
                        + " 2026.1103.145246, the condition its own RELEASE_PUBLISHERS javadoc"
                        + " names for joining)",
                "userflows", LIST_OMISSION,
                "coding-agents", LIST_OMISSION,
                "runner", LIST_OMISSION,
                "ci-daemon", LIST_OMISSION,
                "oci", LIST_OMISSION + " (qits-workspace-oci's Dockerfile pins"
                        + " qits/build-images/node-browser-base)");
        assertThat(new LinkedHashSet<>(order.replays()))
                .as("replays = RELEASE_PUBLISHERS less %s plus %s", notDerived, onlyDerived)
                .containsExactlyInAnyOrderElementsOf(
                        expected(PlatformModel.RELEASE_PUBLISHERS, notDerived, onlyDerived));
    }

    @Test
    void thePushesAreTheSeededReposWithEveryDifferenceNamed() {
        Map<String, String> notDerived = named(
                "workspaces-runner-daemon",
                "list stale: retired by the target (qits-1535) and no submodule of the wrapper",
                "spa-workspaces",
                "list stale: the client qits-workspaces stopped serving (qits-1245), no submodule");
        Map<String, String> onlyDerived = named();
        assertThat(new LinkedHashSet<>(order.pushes()))
                .as("pushes = SEEDED_REPOS less %s plus %s", notDerived, onlyDerived)
                .containsExactlyInAnyOrderElementsOf(
                        expected(PlatformModel.SEEDED_REPOS, notDerived, onlyDerived));
        assertThat(order.pushes()).as("replays are a subset of pushes")
                .containsAll(order.replays());
        assertThat(order.unnamed()).as("repositories PlatformModel.nameOf cannot name").isEmpty();
    }

    /**
     * Every ordering pair PlatformModelTest (deployables, :697-948) and BootstrapPlanTest
     * (replays, :489-517) assert, decomposed into pairs. A subsequence assertion makes every pair
     * of its members; those its own comment gives no reason for are listed under {@link
     * #DROPPED_DEPLOY_PAIRS} with the reason they are dropped.
     */
    private static final List<String[]> DEPLOY_PAIRS = List.of(
            // theDeployerIsLast / every subsequence ending in "deployments"
            pair("edge", "deployments"), pair("orchestrator", "deployments"),
            pair("maintenance", "deployments"), pair("system", "deployments"),
            pair("orchestrator", "edge"), pair("maintenance", "edge"), pair("system", "edge"),
            // idp second: every later application's tokens are minted by it (the RUNTIME edges)
            pair("idp", "stt"), pair("idp", "projects"), pair("idp", "workspaces"),
            pair("idp", "events"), pair("idp", "mirror"), pair("idp", "artifacts"),
            pair("idp", "githost"), pair("idp", "docs"), pair("idp", "containers"),
            pair("idp", "ci"), pair("idp", "orchestrator"), pair("idp", "maintenance"),
            pair("idp", "system"), pair("idp", "edge"), pair("idp", "deployments"),
            // mirror, artifacts, githost, ci
            pair("mirror", "artifacts"), pair("mirror", "githost"), pair("mirror", "ci"),
            pair("artifacts", "githost"), pair("artifacts", "ci"), pair("githost", "ci"),
            pair("containers", "ci"),
            pair("artifacts", "docs"),
            // artifacts, containers, ci, orchestrator
            pair("artifacts", "containers"), pair("artifacts", "orchestrator"),
            pair("containers", "orchestrator"), pair("ci", "orchestrator"),
            // projects, mirror, artifacts, githost, ci, maintenance — each before maintenance
            pair("projects", "maintenance"), pair("mirror", "maintenance"),
            pair("artifacts", "maintenance"), pair("githost", "maintenance"),
            pair("ci", "maintenance"),
            // containers, ci, orchestrator, maintenance, system
            pair("containers", "maintenance"), pair("orchestrator", "maintenance"),
            pair("containers", "system"), pair("ci", "system"),
            pair("orchestrator", "system"), pair("maintenance", "system"));

    /** Pairs the current tests assert that the derived order does not keep, each with why. */
    private static final Map<String, String> DROPPED_DEPLOY_PAIRS = named(
            "observability before *",
            "dropped: observability first (DEPLOYABLES.getFirst()) quiets OTLP warnings — a"
                    + " preference, not a cutover hazard",
            "observability before docs",
            "dropped: docs' only call to observability is the OTLP export every service makes"
                    + " (qits-docs-service OutboundCallsGuardTest), which is observability first again",
            "projects before mirror, artifacts, githost, ci",
            "dropped: incidental to the maintenance subsequence, whose reason is each before"
                    + " maintenance; qits-githost resolves names from its own index and calls no"
                    + " qits-projects, so no cutover reason puts projects first",
            "containsSequence(mirror, artifacts, githost), containsSequence(containers, ci),"
                    + " DEPLOYABLES.get(1) == idp",
            "dropped: adjacency claims; a topological order guarantees before, never next to");

    private static final List<String[]> REPLAY_PAIRS = List.of(
            pair("integrations-quarkus", "eventstream"),
            // qits-ui-components-jslib's harness package.json pins @qits/angular (devDependencies),
            // which its release build installs: a real ARTIFACT edge, read lockless.
            pair("integrations-angular", "spa-ui-components"),
            pair("integrations-angular", "integrations-quarkus"),
            pair("integrations-angular", "eventstream"),
            pair("oci-workspace", "workspace-daemon"),
            pair("oci-workspace", "projects-daemon"));

    private static final Map<String, String> DROPPED_REPLAY_PAIRS = named(
            "spa-ui-components before integrations-angular, integrations-quarkus, eventstream",
            "listed order wrong: ui-components' package.json pins @qits/angular 2026.1103.125108"
                    + " (devDependencies of the harness its release build installs), so angular is"
                    + " replayed FIRST; the other two pairs are incidental to the subsequence",
            "workspace-daemon before oci-workspace-editor",
            "dropped with the editor's replay (nothing pins qits/workspace-editor); in the pushes"
                    + " the ARTIFACT edge on qits/workspace keeps it");

    private static String[] pair(String before, String after) {
        return new String[] {before, after};
    }

    @Test
    void everyAssertedDeployPairHoldsExceptTheNamedDrops() {
        List<String> broken = new ArrayList<>();
        for (String[] pair : DEPLOY_PAIRS) {
            assertThat(order.deploys()).contains(pair);
            if (order.deploys().indexOf(pair[0]) > order.deploys().indexOf(pair[1])) {
                broken.add(pair[0] + " before " + pair[1]);
            }
        }
        assertThat(broken).as("deploys %s; dropped on purpose: %s", order.deploys(),
                DROPPED_DEPLOY_PAIRS).isEmpty();
        assertThat(order.deploys().getLast()).isEqualTo("deployments");
        assertThat(order.deploys().get(order.deploys().size() - 2)).isEqualTo("edge");
    }

    @Test
    void theDroppedDeployPairsAreReallyNotKept() {
        // A dropped pair the derivation keeps after all is no longer a difference: move it back.
        List<String> deploys = order.deploys();
        assertThat(deploys.getFirst()).as(DROPPED_DEPLOY_PAIRS.get("observability before *"))
                .isNotEqualTo("observability");
        assertThat(deploys.indexOf("docs")).as(DROPPED_DEPLOY_PAIRS.get("observability before docs"))
                .isLessThan(deploys.indexOf("observability"));
        assertThat(deploys.indexOf("githost"))
                .as(DROPPED_DEPLOY_PAIRS.get("projects before mirror, artifacts, githost, ci"))
                .isLessThan(deploys.indexOf("projects"));
    }

    @Test
    void everyAssertedReplayPairHoldsExceptTheNamedDrops() {
        List<String> broken = new ArrayList<>();
        for (String[] pair : REPLAY_PAIRS) {
            assertThat(order.replays()).contains(pair);
            if (order.replays().indexOf(pair[0]) > order.replays().indexOf(pair[1])) {
                broken.add(pair[0] + " before " + pair[1]);
            }
        }
        assertThat(broken).as("replays %s; dropped on purpose: %s", order.replays(),
                DROPPED_REPLAY_PAIRS).isEmpty();
        assertThat(order.pushes()).containsSubsequence("workspace-daemon", "oci-workspace-editor");
    }
}
